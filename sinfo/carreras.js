const nombresAreas = {
    ingenieria: "Ingeniería y Tecnología",
    salud: "Salud",
    economia: "Economía y Administración",
    sociales: "Ciencias Sociales",
    educacion: "Educación",
    arte: "Arte y Comunicación",
    naturales: "Ciencias Naturales"
};

const buscador = document.getElementById("buscador-carreras");

const filtroUniversidad = document.getElementById("filtro-universidad");

const filtroArea = document.getElementById("filtro-area");

const contenedor = document.getElementById("contenedor-carreras");

const contador = document.getElementById("contador-carreras");

const sinResultados = document.getElementById("sin-resultados");

function mostrarCarreras(lista) {

    contenedor.innerHTML = "";

    lista.forEach(function(carrera) {

        const tarjeta = document.createElement("article");

        tarjeta.className = "carrera-card";

        let universidadesHTML = "";

        carrera.universidades.forEach(function(universidad) {

            universidadesHTML += `
                <span>${nombresUniversidades[universidad]}</span>
            `;

        });

        tarjeta.innerHTML = `

            <div class="icono-carrera">
                ${carrera.icono}
            </div>

            <div class="contenido-card">

                <span class="area">
                    ${nombresAreas[carrera.area]}
                </span>

                <h3>
                    ${carrera.nombre}
                </h3>

                <p>
                    Formación profesional relacionada con el área de
                    ${nombresAreas[carrera.area].toLowerCase()}.
                </p>

                <div class="universidades">
                    ${universidadesHTML}
                </div>

            </div>

        `;

        contenedor.appendChild(tarjeta);

    });

    contador.textContent =
        lista.length === 1
            ? "1 carrera encontrada"
            : lista.length + " carreras encontradas";

    if (lista.length === 0) {

        sinResultados.style.display = "block";

    } else {

        sinResultados.style.display = "none";

    }

}

function filtrarCarreras() {

    const texto = buscador.value
        .toLowerCase()
        .trim();

    const universidad = filtroUniversidad.value;

    const area = filtroArea.value;

    const resultado = carreras.filter(function(carrera) {

        const coincideTexto =
            carrera.nombre
                .toLowerCase()
                .includes(texto);

        const coincideUniversidad =
            universidad === "todas" ||
            carrera.universidades.includes(universidad);

        const coincideArea =
            area === "todas" ||
            carrera.area === area;

        return (
            coincideTexto &&
            coincideUniversidad &&
            coincideArea
        );

    });

    mostrarCarreras(resultado);

}

buscador.addEventListener(
    "input",
    filtrarCarreras
);

filtroUniversidad.addEventListener(
    "change",
    filtrarCarreras
);

filtroArea.addEventListener(
    "change",
    filtrarCarreras
);

mostrarCarreras(carreras);